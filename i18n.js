function initI18n() {
  const toggleHTML = `<select id="app-lang-switcher" aria-label="App Language">
    <option value="en">🇺🇸 EN</option>
    <option value="vi">🇻🇳 VI</option>
  </select>`;
  const optionsDiv = document.querySelector('.preview-options');
  if(optionsDiv && !document.getElementById('app-lang-switcher')) {
      optionsDiv.insertAdjacentHTML('afterbegin', toggleHTML);
  }

  let currentLang = localStorage.getItem('appLang') || 'en';
  
  const switcher = document.getElementById('app-lang-switcher');
  if(switcher) {
      switcher.value = currentLang;
      switcher.addEventListener('change', (e) => {
        localStorage.setItem('appLang', e.target.value);
        window.location.reload();
      });
  }

  function translateDOM(root) {
    if (currentLang === 'en') return;
    
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null, false);
    let node;
    while (node = walker.nextNode()) {
      let text = node.nodeValue.trim();
      if (text && window.i18nDict[text]) {
        node.nodeValue = node.nodeValue.replace(text, window.i18nDict[text]);
      } else if (text) {
          for (const [en, vi] of Object.entries(window.i18nDict)) {
              if (node.nodeValue.includes(en)) {
                  node.nodeValue = node.nodeValue.replace(en, vi);
              }
          }
      }
    }
    
    root.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
       const p = el.getAttribute('placeholder');
       if (p && window.i18nDict[p]) el.setAttribute('placeholder', window.i18nDict[p]);
    });
    
    root.querySelectorAll('*[title]').forEach(el => {
       const p = el.getAttribute('title');
       if (p && window.i18nDict[p]) el.setAttribute('title', window.i18nDict[p]);
    });
  }

  if (typeof window.render === 'function') {
      const originalRender = window.render;
      window.render = function() {
        originalRender.apply(this, arguments);
        if (currentLang === 'vi') {
            translateDOM(document.body);
        }
      };
      
      if (currentLang === 'vi') {
          translateDOM(document.body);
      }
  }
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initI18n);
} else {
  initI18n();
}
